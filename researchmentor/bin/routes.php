#!/usr/bin/env php
<?php
declare(strict_types=1);

/** Prints the route table as Markdown (used to generate docs/API.md): php bin/routes.php > docs/API.md */
require __DIR__ . '/../bootstrap/database.php';

$app = new App\Support\Application();
$rows = $app->router()->routes();
usort($rows, fn($a, $b) => [$a['pattern'], $a['method']] <=> [$b['pattern'], $b['method']]);
echo "# ResearchMentor AI - route reference\n\n";
echo "Generated by `php bin/routes.php`. All `/api` responses are JSON: `{\"success\":true,\"data\":...,\"meta\":...}` or `{\"success\":false,\"error\":{\"code\",\"message\",\"details\"}}`.\n";
echo "Identifiers in paths (`{id}`, `{pid}`, ...) are opaque UUIDs. State-changing requests need the `X-CSRF-Token` header (see `GET /api/auth/csrf`). `auth` = signed-in session required; authorization is then enforced per resource by policies.\n\n";
echo "| Method | Path | Middleware |\n|---|---|---|\n";
foreach ($rows as $r) {
    printf("| %s | `%s` | %s |\n", $r['method'], $r['pattern'], implode(', ', $r['middleware']) ?: '-');
}
printf("\n%d routes.\n", count($rows));
