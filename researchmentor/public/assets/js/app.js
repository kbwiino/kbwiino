/* ResearchMentor AI - shared client helpers (vanilla JS, Fetch API). No inline scripts (CSP). */
(function () {
  'use strict';
  const RM = (window.RM = window.RM || { pages: {} });

  RM.csrf = () => (document.querySelector('meta[name="csrf-token"]') || {}).content || '';
  RM.setCsrf = (t) => { const m = document.querySelector('meta[name="csrf-token"]'); if (m && t) m.content = t; };
  RM.roles = () => (document.body.dataset.roles || '').split(',').filter(Boolean);
  RM.hasRole = (...r) => r.some((x) => RM.roles().includes(x));

  /** HTML-escape. Every dynamic string rendered with innerHTML MUST go through this. */
  RM.esc = (v) => String(v ?? '').replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
  RM.nl2br = (v) => RM.esc(v).replace(/\n/g, '<br>');

  RM.api = async function (method, url, body, opts = {}) {
    const init = { method, headers: { Accept: 'application/json', 'X-CSRF-Token': RM.csrf() }, credentials: 'same-origin' };
    if (body instanceof FormData) {
      init.body = body;
    } else if (body !== undefined && body !== null) {
      init.headers['Content-Type'] = 'application/json';
      init.body = JSON.stringify(body);
    }
    let res;
    try { res = await fetch(url, init); } catch (e) { throw { status: 0, code: 'network', message: 'Network error. Check your connection.' }; }
    if (opts.raw) return res;
    let json = null;
    try { json = await res.json(); } catch (e) { /* non-JSON */ }
    if (res.status === 401 && !opts.noRedirect && !url.includes('/auth/')) { location.href = '/login'; throw { status: 401, code: 'unauthenticated', message: 'Please sign in.' }; }
    if (!res.ok || !json || json.success === false) {
      const err = (json && json.error) || { code: 'error', message: 'Request failed.' };
      throw { status: res.status, code: err.code, message: err.message, details: err.details || {} };
    }
    return opts.full ? json : json.data;
  };
  RM.get = (u) => RM.api('GET', u);
  RM.post = (u, b) => RM.api('POST', u, b === undefined ? {} : b);
  RM.put = (u, b) => RM.api('PUT', u, b);
  RM.del = (u) => RM.api('DELETE', u);

  RM.alert = function (msg, type = 'danger', target = '#alerts') {
    const box = document.querySelector(target); if (!box) return;
    box.innerHTML = `<div class="alert alert-${type} alert-dismissible fade show" role="alert">${RM.esc(msg)}<button type="button" class="btn-close" data-bs-dismiss="alert" aria-label="Close"></button></div>`;
    window.scrollTo({ top: 0, behavior: 'smooth' });
  };
  RM.showError = (e, target) => {
    let m = e.message || 'Something went wrong.';
    if (e.details && Object.keys(e.details).length) {
      m += ' ' + Object.entries(e.details).map(([k, v]) => `${k}: ${[].concat(v).join(' ')}`).join(' | ');
    }
    RM.alert(m, 'danger', target);
  };

  RM.fmtDate = (s) => { if (!s) return '—'; const d = new Date(String(s).replace(' ', 'T') + (String(s).includes('Z') ? '' : 'Z')); return isNaN(d) ? RM.esc(s) : d.toLocaleDateString(undefined, { year: 'numeric', month: 'short', day: 'numeric' }); };
  RM.fmtDateTime = (s) => { if (!s) return '—'; const d = new Date(String(s).replace(' ', 'T') + 'Z'); return isNaN(d) ? RM.esc(s) : d.toLocaleString(undefined, { dateStyle: 'medium', timeStyle: 'short' }); };
  RM.label = (s) => RM.esc(String(s || '').replace(/_/g, ' ').replace(/^\w/, (c) => c.toUpperCase()));

  const SEV = { critical: 'danger', high: 'danger', medium: 'warning', low: 'secondary' };
  RM.sevBadge = (s) => `<span class="badge text-bg-${SEV[s] || 'secondary'}">${RM.label(s)}</span>`;
  RM.originBadge = (o) => ({
    ai_suggestion: '<span class="badge badge-ai" title="Generated by AI - requires human review"><i class="bi bi-robot"></i> AI suggestion</span>',
    student: '<span class="badge badge-student">Student</span>',
    supervisor: '<span class="badge badge-human"><i class="bi bi-person-check"></i> Supervisor</span>',
    official: '<span class="badge badge-human"><i class="bi bi-patch-check"></i> Official</span>',
  }[o] || `<span class="badge text-bg-secondary">${RM.label(o)}</span>`);

  RM.aiDisclaimer = () => '<div class="ai-box small"><i class="bi bi-robot"></i> <strong>AI-generated suggestion.</strong> This is not a grade, an approval or an official academic decision. A human supervisor must review it.</div>';

  RM.spinner = (text = 'Loading…') => `<div class="text-center py-4 text-muted" role="status"><div class="spinner-border spinner-border-sm"></div> ${RM.esc(text)}</div>`;

  RM.charts = {};
  RM.chart = (id, config) => { const el = document.getElementById(id); if (!el || !window.Chart) return; if (RM.charts[id]) RM.charts[id].destroy(); RM.charts[id] = new Chart(el, config); };

  RM.formData = (form) => { const o = {}; new FormData(form).forEach((v, k) => { o[k] = v; }); return o; };

  document.addEventListener('DOMContentLoaded', () => {
    const logout = document.getElementById('logout-btn');
    if (logout) logout.addEventListener('click', async () => {
      try { await RM.post('/api/auth/logout'); } catch (e) { /* ignore */ }
      location.href = '/login';
    });
    const root = document.getElementById('page-root');
    if (root && RM.pages[root.dataset.page]) {
      Promise.resolve(RM.pages[root.dataset.page](root, root.dataset.id, root.dataset.id2)).catch((e) => {
        root.innerHTML = `<div class="alert alert-danger">${RM.esc(e.message || 'Failed to load this page.')}</div>`;
      });
    }
    const nc = document.getElementById('notif-count');
    if (nc) RM.get('/api/notifications?unread=1&per_page=1').then((d) => { if (d.unread_count > 0) { nc.textContent = d.unread_count; nc.classList.remove('d-none'); } }).catch(() => {});
  });
})();
