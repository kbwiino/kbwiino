CREATE TABLE research_projects (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  uuid CHAR(36) NOT NULL,
  institution_id BIGINT UNSIGNED NOT NULL,
  faculty_id BIGINT UNSIGNED NOT NULL,
  department_id BIGINT UNSIGNED NOT NULL,
  programme_id BIGINT UNSIGNED NOT NULL,
  academic_year_id BIGINT UNSIGNED NOT NULL,
  owner_user_id BIGINT UNSIGNED NOT NULL,
  degree_level ENUM('masters','phd') NOT NULL,
  title VARCHAR(500) NOT NULL,
  research_area VARCHAR(255) NOT NULL,
  problem_statement TEXT NOT NULL,
  purpose TEXT NOT NULL,
  background TEXT NULL,
  scope TEXT NULL,
  significance TEXT NULL,
  paradigm VARCHAR(100) NULL,
  approach ENUM('quantitative','qualitative','mixed','other') NOT NULL,
  design VARCHAR(255) NOT NULL,
  population TEXT NULL,
  sampling_approach TEXT NULL,
  data_collection_methods TEXT NULL,
  data_analysis_methods TEXT NULL,
  ethics_information TEXT NULL,
  stage ENUM('topic_selection','proposal_development','proposal_defense','ethics_approval','data_collection','data_analysis','thesis_writing','internal_review','examination','viva','completed') NOT NULL DEFAULT 'topic_selection',
  status ENUM('draft','active','on_hold','completed','archived') NOT NULL DEFAULT 'draft',
  ai_consent_at DATETIME NULL,
  ai_consent_by BIGINT UNSIGNED NULL,
  archived_at DATETIME NULL,
  created_by BIGINT UNSIGNED NOT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uq_projects_uuid (uuid),
  KEY ix_projects_institution_stage (institution_id, stage),
  KEY ix_projects_department (department_id),
  KEY ix_projects_owner (owner_user_id),
  KEY ix_projects_status (status),
  CONSTRAINT fk_projects_institution FOREIGN KEY (institution_id) REFERENCES institutions(id) ON DELETE RESTRICT,
  CONSTRAINT fk_projects_faculty FOREIGN KEY (faculty_id) REFERENCES faculties(id) ON DELETE RESTRICT,
  CONSTRAINT fk_projects_department FOREIGN KEY (department_id) REFERENCES departments(id) ON DELETE RESTRICT,
  CONSTRAINT fk_projects_programme FOREIGN KEY (programme_id) REFERENCES programmes(id) ON DELETE RESTRICT,
  CONSTRAINT fk_projects_year FOREIGN KEY (academic_year_id) REFERENCES academic_years(id) ON DELETE RESTRICT,
  CONSTRAINT fk_projects_owner FOREIGN KEY (owner_user_id) REFERENCES users(id) ON DELETE RESTRICT,
  CONSTRAINT fk_projects_consent_by FOREIGN KEY (ai_consent_by) REFERENCES users(id) ON DELETE SET NULL,
  CONSTRAINT fk_projects_created_by FOREIGN KEY (created_by) REFERENCES users(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

