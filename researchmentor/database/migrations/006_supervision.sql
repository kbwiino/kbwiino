CREATE TABLE supervision_sessions (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  uuid CHAR(36) NOT NULL,
  project_id BIGINT UNSIGNED NOT NULL,
  title VARCHAR(255) NOT NULL,
  scheduled_at DATETIME NOT NULL,
  duration_minutes SMALLINT UNSIGNED NOT NULL DEFAULT 60,
  location VARCHAR(255) NULL,
  status ENUM('scheduled','completed','cancelled') NOT NULL DEFAULT 'scheduled',
  discussion_notes MEDIUMTEXT NULL,
  decisions MEDIUMTEXT NULL,
  ai_brief MEDIUMTEXT NULL,
  ai_brief_generated_at DATETIME NULL,
  outcome MEDIUMTEXT NULL,
  outcome_recorded_by BIGINT UNSIGNED NULL,
  outcome_recorded_at DATETIME NULL,
  created_by BIGINT UNSIGNED NOT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uq_sessions_uuid (uuid),
  KEY ix_sessions_project (project_id, scheduled_at),
  KEY ix_sessions_when (scheduled_at, status),
  CONSTRAINT fk_sessions_project FOREIGN KEY (project_id) REFERENCES research_projects(id) ON DELETE CASCADE,
  CONSTRAINT fk_sessions_created_by FOREIGN KEY (created_by) REFERENCES users(id) ON DELETE RESTRICT,
  CONSTRAINT fk_sessions_outcome_by FOREIGN KEY (outcome_recorded_by) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE supervision_agendas (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  session_id BIGINT UNSIGNED NOT NULL,
  position INT UNSIGNED NOT NULL DEFAULT 0,
  item VARCHAR(500) NOT NULL,
  origin ENUM('student','supervisor','ai_suggestion') NOT NULL DEFAULT 'supervisor',
  state ENUM('proposed','accepted','rejected') NOT NULL DEFAULT 'accepted',
  decided_by BIGINT UNSIGNED NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  KEY ix_agendas_session (session_id, position),
  CONSTRAINT fk_agendas_session FOREIGN KEY (session_id) REFERENCES supervision_sessions(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE supervision_action_items (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  uuid CHAR(36) NOT NULL,
  project_id BIGINT UNSIGNED NOT NULL,
  session_id BIGINT UNSIGNED NULL,
  document_id BIGINT UNSIGNED NULL,
  kind ENUM('task','revision_request') NOT NULL DEFAULT 'task',
  title VARCHAR(300) NOT NULL,
  description TEXT NULL,
  assigned_to BIGINT UNSIGNED NOT NULL,
  created_by BIGINT UNSIGNED NOT NULL,
  origin ENUM('student','supervisor','ai_suggestion') NOT NULL DEFAULT 'supervisor',
  due_date DATE NULL,
  state ENUM('proposed','open','in_progress','submitted','completed','cancelled') NOT NULL DEFAULT 'open',
  student_response TEXT NULL,
  submitted_at DATETIME NULL,
  completed_at DATETIME NULL,
  completed_by BIGINT UNSIGNED NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uq_tasks_uuid (uuid),
  KEY ix_tasks_project (project_id, state),
  KEY ix_tasks_assignee (assigned_to, state, due_date),
  CONSTRAINT fk_tasks_project FOREIGN KEY (project_id) REFERENCES research_projects(id) ON DELETE CASCADE,
  CONSTRAINT fk_tasks_session FOREIGN KEY (session_id) REFERENCES supervision_sessions(id) ON DELETE SET NULL,
  CONSTRAINT fk_tasks_document FOREIGN KEY (document_id) REFERENCES documents(id) ON DELETE SET NULL,
  CONSTRAINT fk_tasks_assignee FOREIGN KEY (assigned_to) REFERENCES users(id) ON DELETE CASCADE,
  CONSTRAINT fk_tasks_creator FOREIGN KEY (created_by) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE supervision_comments (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  uuid CHAR(36) NOT NULL,
  project_id BIGINT UNSIGNED NOT NULL,
  session_id BIGINT UNSIGNED NULL,
  action_item_id BIGINT UNSIGNED NULL,
  parent_id BIGINT UNSIGNED NULL,
  author_id BIGINT UNSIGNED NOT NULL,
  origin ENUM('student','supervisor') NOT NULL,
  body TEXT NOT NULL,
  status ENUM('open','resolved') NOT NULL DEFAULT 'open',
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE KEY uq_scomments_uuid (uuid),
  KEY ix_scomments_project (project_id, status),
  CONSTRAINT fk_scomments_project FOREIGN KEY (project_id) REFERENCES research_projects(id) ON DELETE CASCADE,
  CONSTRAINT fk_scomments_session FOREIGN KEY (session_id) REFERENCES supervision_sessions(id) ON DELETE CASCADE,
  CONSTRAINT fk_scomments_task FOREIGN KEY (action_item_id) REFERENCES supervision_action_items(id) ON DELETE CASCADE,
  CONSTRAINT fk_scomments_parent FOREIGN KEY (parent_id) REFERENCES supervision_comments(id) ON DELETE CASCADE,
  CONSTRAINT fk_scomments_author FOREIGN KEY (author_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE supervision_approvals (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  uuid CHAR(36) NOT NULL,
  project_id BIGINT UNSIGNED NOT NULL,
  subject_type ENUM('document_version','constitution','proposal_change','ai_review','stage_change','session_outcome') NOT NULL,
  subject_id BIGINT UNSIGNED NOT NULL,
  decision ENUM('approved','revision_requested','rejected','acknowledged') NOT NULL,
  notes TEXT NULL,
  decided_by BIGINT UNSIGNED NOT NULL,
  decided_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE KEY uq_approvals_uuid (uuid),
  KEY ix_approvals_subject (subject_type, subject_id),
  KEY ix_approvals_project (project_id, decided_at),
  CONSTRAINT fk_approvals_project FOREIGN KEY (project_id) REFERENCES research_projects(id) ON DELETE CASCADE,
  CONSTRAINT fk_approvals_user FOREIGN KEY (decided_by) REFERENCES users(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
